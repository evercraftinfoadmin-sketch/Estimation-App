const { launch, FILE, OUT, FIXTURES, MODE } = require('../helpers');
let pass=0,fail=0; const ok=(c,m)=>{c?pass++:fail++;console.log((c?'PASS ':'FAIL ')+m);};
(async()=>{
  const b=await launch(); const p=await b.newPage({viewport:{width:1500,height:900}});
  const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error')errs.push(m.text());});
  let answer=true; const dialogs=[]; p.on('dialog',d=>{dialogs.push(d.message()); answer?d.accept():d.dismiss();});
  await p.goto(FILE+'#crm');
  const projects=()=>p.evaluate(()=>JSON.parse(localStorage.getItem(storageKey('constructionEstimatorCRM'))||'[]'));
  const newLead=async n=>{await p.click('#btnNewLead');await p.fill('#pmClientName',n);await p.click('#projectForm button[type=submit]');};
  for (const n of ['Lead A','Lead B','Job C']) await newLead(n);
  await p.locator('.kcard',{hasText:'Job C'}).locator('[data-action=to-prospect]').click();
  await p.locator('.kcard',{hasText:'Job C'}).locator('[data-action=to-job]').click();
  ok(await p.locator('.kcard .kcard-delete').count()===3,'every card has a delete icon (lead, lead, job)');
  answer=false;
  await p.locator('.kcard',{hasText:'Lead A'}).locator('.kcard-delete').click();
  ok((await projects()).length===3 && dialogs.at(-1).includes('Delete CRM project for Lead A'),'click asks for confirmation; Cancel keeps the lead');
  answer=true;
  await p.locator('.kcard',{hasText:'Lead A'}).locator('.kcard-delete').click();
  ok(!(await projects()).some(x=>x.clientName==='Lead A') && await p.locator('.kcard',{hasText:'Lead A'}).count()===0,'lead deleted with one click + confirm');
  await p.locator('.kcard',{hasText:'Job C'}).locator('.kcard-delete').click();
  ok(!(await projects()).some(x=>x.clientName==='Job C'),'card in Client / Job can be deleted too');
  await p.locator('.kcard',{hasText:'Lead B'}).locator('[data-action=open]').click();
  await p.click('#pmDelete');
  ok((await projects()).length===0 && !(await p.isVisible('#projectModal')),'Delete inside the project window still works');
  await p.reload();
  ok((await p.locator('.kcard').count())===0,'deletion persists after reload');
  await newLead('Mobile Lead'); await p.setViewportSize({width:390,height:844});
  ok(await p.locator('.kcard',{hasText:'Mobile Lead'}).locator('.kcard-delete').isVisible(),'delete icon visible on mobile');
  await p.screenshot({path:OUT+'/delete.png'});
  ok(errs.length===0,'no console errors '+JSON.stringify(errs));
  console.log(`\n${pass} passed, ${fail} failed`); await b.close();
})();
